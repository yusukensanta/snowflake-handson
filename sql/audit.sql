-- Audit queries for the AUDITOR persona. ACCOUNT_USAGE views lag by up to ~2-3 hours.

-- 1) Who read HEALTH-tagged columns in the last 7 days?
SELECT ah.QUERY_START_TIME, ah.USER_NAME, col.value:"columnName"::STRING AS COLUMN_NAME, ah.QUERY_ID
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY ah,
     LATERAL FLATTEN(ah.BASE_OBJECTS_ACCESSED) obj,
     LATERAL FLATTEN(obj.value:"columns") col
WHERE ah.QUERY_START_TIME > DATEADD('day', -7, CURRENT_TIMESTAMP())
  AND col.value:"columnName"::STRING IN (
        SELECT COLUMN_NAME FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
        WHERE TAG_NAME = 'SENSITIVITY' AND TAG_VALUE = 'HEALTH' AND DOMAIN = 'COLUMN')
ORDER BY ah.QUERY_START_TIME DESC;

-- 2) Role grant changes in the last 7 days (separation-of-duties review)
SELECT CREATED_ON, GRANTEE_NAME, ROLE, GRANTED_BY, DELETED_ON
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS
WHERE CREATED_ON > DATEADD('day', -7, CURRENT_TIMESTAMP()) OR DELETED_ON > DATEADD('day', -7, CURRENT_TIMESTAMP())
ORDER BY CREATED_ON DESC;

-- 3) Where does sensitive data flow? (object dependencies, one level)
SELECT REFERENCED_OBJECT_NAME, REFERENCING_OBJECT_NAME, REFERENCING_OBJECT_DOMAIN
FROM SNOWFLAKE.ACCOUNT_USAGE.OBJECT_DEPENDENCIES
WHERE REFERENCED_DATABASE = 'HANBIT_RAW';
