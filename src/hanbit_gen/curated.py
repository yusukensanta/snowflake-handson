"""Generate the CURATED layer (Dynamic Tables) and data-quality (DMF) SQL from SCHEMAS."""
from __future__ import annotations

from .schema import DOMAINS, SCHEMAS


def curated_dynamic_tables_sql() -> str:
    out = ["-- GENERATED by `scripts/gen-data --execute --emit-curated sql/curated.sql`. Do not edit.\n-- IF NOT EXISTS on purpose: CREATE OR REPLACE would drop the policies attached to the table.\n"]
    for d in DOMAINS:
        cols = [c.name.upper() for c in SCHEMAS[d]]
        key = cols[0]
        select = ",\n  ".join(cols)
        if "CUSTOMER_ID" in cols:
            select += ",\n  SHA2(CUSTOMER_ID || '|hanbit-pseudo-v1', 256) AS CUSTOMER_PSEUDO_ID"
        out.append(
            f"CREATE DYNAMIC TABLE IF NOT EXISTS HANBIT_CURATED.{d.upper()}.{d.upper()}\n"
            f"  TARGET_LAG = '1 hour'\n  WAREHOUSE = TRANSFORM_WH\n  AS\n"
            f"SELECT\n  {select}\nFROM HANBIT_RAW.{d.upper()}.{d.upper()}\n"
            f"QUALIFY ROW_NUMBER() OVER (PARTITION BY {key} ORDER BY {key}) = 1;\n"
        )
    return "\n".join(out)


def dmf_sql() -> str:
    out = ["-- GENERATED. Data metric functions on curated key columns.\n"]
    for d in DOMAINS:
        key = SCHEMAS[d][0].name.upper()
        t = f"HANBIT_CURATED.{d.upper()}.{d.upper()}"
        out.append(f"ALTER TABLE {t} SET DATA_METRIC_SCHEDULE = '60 MINUTE';")
        for fn in ("NULL_COUNT", "DUPLICATE_COUNT"):
            out.append(f"ALTER TABLE {t} ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.{fn} ON ({key});")
    return "\n".join(out) + "\n"
