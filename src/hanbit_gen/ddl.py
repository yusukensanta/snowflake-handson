"""Generate RAW-layer DDL from SCHEMAS so SQL, Terraform tags and data never drift apart."""
from __future__ import annotations

from .schema import DOMAINS, SCHEMAS


def raw_ddl() -> str:
    out = ["-- GENERATED by `scripts/gen-data --execute --emit-ddl sql/raw_tables.sql`. Do not edit.\n"]
    for d in DOMAINS:
        cols = ",\n".join(f"  {c.name.upper()} {c.type}" for c in SCHEMAS[d])
        for table in (d.upper(), f"{d.upper()}_STREAM"):
            out.append(f"CREATE TABLE IF NOT EXISTS HANBIT_RAW.{d.upper()}.{table} (\n{cols}\n);\n")
    return "\n".join(out)
